// Generates src/util/joiningTypeData.js from the Unicode Character Database
// file DerivedJoiningType.txt (the Joining_Type property used for cursive
// shaping of Arabic, Syriac, N'Ko, Adlam and similar scripts).
//
// Usage:
//   node scripts/generateJoiningType.mjs path/to/DerivedJoiningType.txt
//
// The data file is published at
// https://www.unicode.org/Public/<version>/ucd/extracted/DerivedJoiningType.txt
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const source = process.argv[2];
if (!source) {
  console.error(
    "Usage: node scripts/generateJoiningType.mjs <DerivedJoiningType.txt>",
  );
  process.exit(1);
}

// Transparent (T) is left out: it is nearly the general categories Mn, Me
// and Cf, which the lookup tests with a regular expression instead.
const CODES = { R: 1, L: 2, D: 3, C: 4 };
const values = new Uint8Array(0x110000);
const text = readFileSync(source, "utf8");
const version = text.match(/DerivedJoiningType-([\d.]+)\.txt/)?.[1] ?? "";

for (const line of text.split("\n")) {
  const entry = line.match(/^([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*(\w+)/);
  if (!entry) continue;

  const code = CODES[entry[2]];
  if (code === undefined) continue;

  const [start, end = start] = entry[1]
    .split("..")
    .map((hex) => parseInt(hex, 16));
  values.fill(code, start, end + 1);
}

const rows = [];
let start = 0;
for (let codePoint = 1; codePoint <= 0x110000; codePoint++) {
  if (codePoint === 0x110000 || values[codePoint] !== values[start]) {
    if (values[start] !== 0) {
      rows.push(
        `0x${start.toString(16)},0x${(codePoint - 1).toString(16)},${values[start]}`,
      );
    }
    start = codePoint;
  }
}

const lines = [];
for (let index = 0; index < rows.length; index += 4) {
  lines.push(`  ${rows.slice(index, index + 4).join(", ")},`);
}

const output = `// Generated by scripts/generateJoiningType.mjs from the Unicode Character
// Database file DerivedJoiningType.txt. Do not edit by hand.
export const JOINING_TYPE_UNICODE_VERSION = "${version}";

// Flat triples of [first code point, last code point, value]. 1 = R
// (Right_Joining), 2 = L (Left_Joining), 3 = D (Dual_Joining), 4 = C
// (Join_Causing). Transparent code points are not listed.
// prettier-ignore
export const JOINING_TYPE_RANGES = [
${lines.join("\n")}
];
`;

const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/util/joiningTypeData.js",
);
writeFileSync(target, output);
console.log(`Wrote ${rows.length} ranges (Unicode ${version}) to ${target}`);
