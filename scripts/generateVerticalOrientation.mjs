// Generates src/util/verticalOrientationData.js from the Unicode Character
// Database file VerticalOrientation.txt (UAX #50).
//
// Usage:
//   node scripts/generateVerticalOrientation.mjs path/to/VerticalOrientation.txt
//
// The data file is published at
// https://www.unicode.org/Public/<version>/ucd/VerticalOrientation.txt
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const source = process.argv[2];
if (!source) {
  console.error(
    "Usage: node scripts/generateVerticalOrientation.mjs <VerticalOrientation.txt>",
  );
  process.exit(1);
}

const CODES = { R: 0, U: 1, Tu: 2, Tr: 3 };
const values = new Uint8Array(0x110000);
const text = readFileSync(source, "utf8");
const version = text.match(/VerticalOrientation-([\d.]+)\.txt/)?.[1] ?? "";

const apply = (range, value) => {
  const code = CODES[value];
  if (code === undefined) throw new Error(`Unknown value: ${value}`);
  const [start, end = start] = range
    .split("..")
    .map((hex) => parseInt(hex, 16));
  values.fill(code, start, end + 1);
};

// Defaults for unassigned code points come first so explicit lines override.
for (const line of text.split("\n")) {
  const missing = line.match(/^# @missing:\s*([0-9A-F.]+)\s*;\s*(\w+)/);
  if (missing) apply(missing[1], missing[2]);
}
for (const line of text.split("\n")) {
  const entry = line.match(/^([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*(\w+)/);
  if (entry) apply(entry[1], entry[2]);
}

const ranges = [];
let start = 0;
for (let codePoint = 1; codePoint <= 0x110000; codePoint++) {
  if (codePoint === 0x110000 || values[codePoint] !== values[start]) {
    if (values[start] !== CODES.R) {
      ranges.push(start, codePoint - 1, values[start]);
    }
    start = codePoint;
  }
}

const rows = [];
for (let index = 0; index < ranges.length; index += 3) {
  rows.push(
    `0x${ranges[index].toString(16)},0x${ranges[index + 1].toString(16)},${ranges[index + 2]}`,
  );
}
const lines = [];
for (let index = 0; index < rows.length; index += 4) {
  lines.push(`  ${rows.slice(index, index + 4).join(", ")},`);
}

const output = `// Generated by scripts/generateVerticalOrientation.mjs from the Unicode
// Character Database file VerticalOrientation.txt. Do not edit by hand.
export const VERTICAL_ORIENTATION_UNICODE_VERSION = "${version}";

// Flat triples of [first code point, last code point, value]. Code points
// outside every range are R (rotated). 1 = U, 2 = Tu, 3 = Tr.
// prettier-ignore
export const VERTICAL_ORIENTATION_RANGES = [
${lines.join("\n")}
];
`;

const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/util/verticalOrientationData.js",
);
writeFileSync(target, output);
console.log(`Wrote ${rows.length} ranges (Unicode ${version}) to ${target}`);
